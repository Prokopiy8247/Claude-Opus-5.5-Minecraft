# ---------------------------------------------------------------------------- ramps
def shade(hexc, factor):
    h = hexc.lstrip('#')
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    f = lambda v: max(0, min(255, int(v * factor)))
    return "#%02x%02x%02x" % (f(r), f(g), f(b))

def ramp(hexc):
    return [shade(hexc, 0.45), shade(hexc, 0.7), hexc, shade(hexc, 1.22), shade(hexc, 1.45)]

