T = {}

WARN = []

def tpl(name, *rows):
    rows = list(rows)
    if len(rows) != 16:
        WARN.append("%s: %d rows" % (name, len(rows)))
        rows = (rows + ["." * 16] * 16)[:16]
    fixed = []
    for r in rows:
        if len(r) != 16:
            WARN.append("%s: row %r has %d chars" % (name, r, len(r)))
        r = r.replace(" ", ".")
        fixed.append((r + "." * 16)[:16])
    T[name] = fixed

