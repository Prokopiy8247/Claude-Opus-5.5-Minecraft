def emit():
    lines = []
    a = lines.append
    a("class_name ItemSpriteData")
    a("extends RefCounted")
    a("## Original 16x16 item sprite templates (ASCII) and per-item colour ramps.")
    a("## Generated by tools/gen_item_sprites.py -- edit the generator, not this file by hand.")
    a("##")
    a("## Template characters:")
    a("##   '.' transparent, '1'..'5' primary ramp (dark -> light), 'a'..'e' secondary ramp,")
    a("##   'h'/'H' wood handle, 'k' outline, 'w' white highlight.")
    a("")
    a('const HANDLE_DARK := "#4a3319"')
    a('const HANDLE_LIGHT := "#8a6236"')
    a("")
    a("const TEMPLATES := {")
    for name in sorted(T):
        rows = T[name]
        a('\t"%s": [' % name)
        for r in rows:
            a('\t\t"%s",' % r)
        a("\t],")
    a("}")
    a("")
    a("## item name -> [template, primary ramp, secondary ramp]")
    a("const ITEMS := {")
    for name in sorted(ITEMS):
        t, p, s = ITEMS[name]
        ps = ", ".join('"%s"' % c for c in p)
        ss = ", ".join('"%s"' % c for c in s)
        a('\t"%s": ["%s", [%s], [%s]],' % (name, t, ps, ss))
    a("}")
    a("")
    a("")
    a("static func has_item(n: String) -> bool:")
    a("\treturn ITEMS.has(n)")
    a("")
    out = "\n".join(lines)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(out)
    print("wrote %s: %d templates, %d items" % (OUT, len(T), len(ITEMS)))
    missing = sorted(set(v[0] for v in ITEMS.values()) - set(T))
    if missing:
        print("MISSING TEMPLATES:", missing)
    print("%d row warnings (auto-fixed)" % len(WARN))


if __name__ == "__main__":
    emit()
